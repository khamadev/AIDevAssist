import subprocess
from pathlib import Path

from ai_test_tool.agents import reliability


def _write(path: Path, content: str) -> None:
    path.write_text(content, encoding="utf-8")


def test_run_reports_none_when_nothing_to_check(tmp_path: Path):
    result = reliability.run(target=str(tmp_path), stage="pre-commit")

    assert result["summary"] == "No generated test found to verify"
    assert result["passed"] is True


def test_run_does_not_pick_up_unrelated_pre_existing_test_files(tmp_path: Path):
    """Regression test: reliability must never grade a random file that
    happens to exist in the repo but isn't part of the current change —
    doing so previously blocked every unrelated commit/push."""
    _write(
        tmp_path / "test_unrelated.py",
        "def test_unrelated():\n    assert True\n",
    )

    result = reliability.run(target=str(tmp_path), stage="pre-commit")

    assert result["summary"] == "No generated test found to verify"
    assert result["passed"] is True


def test_meaningful_passing_disclosed_test_is_reliable_and_compliant(tmp_path: Path):
    test_file = tmp_path / "test_add.py"
    _write(
        test_file,
        "# AI-generated by ai-test-tool\n"
        "def add(a, b):\n"
        "    return a + b\n\n"
        "def test_add():\n"
        "    assert add(2, 3) == 5\n",
    )

    result = reliability.run(target=str(tmp_path), stage="pre-commit", test_path="test_add.py")
    details = result["details"]

    assert details["classification"] == "reliable"
    assert details["is_compliant"] is True
    assert result["passed"] is True


