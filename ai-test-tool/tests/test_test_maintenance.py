def test_run_skips_functions_already_covered_by_an_import(tmp_path: Path, monkeypatch):
    repo = _init_repo(tmp_path)
    source = _seed_source(repo)
    (repo / "tests" / "test_trip_logic.py").write_text(
        "from app.trip_logic import trip_duration_days\n\n\n"
        "def test_trip_duration_days_single_day():\n"
        "    from datetime import date\n"
        "    d = date(2026, 1, 1)\n"
        "    assert trip_duration_days(d, d) == 1\n",
        encoding="utf-8",
    )
    _stage(repo, source)
    monkeypatch.setattr(ai_client, "generate", lambda prompt, **k: GENERATED_TEST)

    result = test_maintenance.run(target=str(repo), stage="pre-commit")

    functions = {g["function"] for g in result["details"]["generated"]}
    assert functions == {"trips_overlap"}
    assert "trip_duration_days" not in functions


def test_run_skips_gracefully_when_ai_is_unavailable(tmp_path: Path, monkeypatch):
    repo = _init_repo(tmp_path)
    source = _seed_source(repo)
    _stage(repo, source)

    def _raise(prompt, **k):
        raise ai_client.AIUnavailable("ANTHROPIC_API_KEY is not set")

    monkeypatch.setattr(ai_client, "generate", _raise)

    result = test_maintenance.run(target=str(repo), stage="pre-commit")

    assert result["details"]["generated"] == []
    assert result["passed"] is False
    assert len(result["details"]["skipped"]) == 2
    assert all("ANTHROPIC_API_KEY" in s["reason"] for s in result["details"]["skipped"])
    # The repo itself must be untouched — no partial/empty test file created.
    assert not (repo / "tests" / "test_trip_logic.py").exists()


def test_run_respects_the_per_run_generation_cap(tmp_path: Path, monkeypatch):
    repo = _init_repo(tmp_path)
    app_dir = repo / "app"
    app_dir.mkdir()
    (app_dir / "__init__.py").write_text("", encoding="utf-8")
    lots_of_functions = "\n\n".join(f"def f{i}():\n    return {i}" for i in range(8))
    source = app_dir / "many.py"
    source.write_text(lots_of_functions + "\n", encoding="utf-8")
    (repo / "tests").mkdir()
    _stage(repo, source)

    calls = []
    monkeypatch.setattr(
        ai_client, "generate", lambda prompt, **k: calls.append(1) or "def test_x():\n    assert True\n"
    )

    result = test_maintenance.run(target=str(repo), stage="pre-commit")

    assert len(calls) == test_maintenance.MAX_FUNCTIONS_PER_RUN
    assert len(result["details"]["generated"]) == test_maintenance.MAX_FUNCTIONS_PER_RUN
    assert len(result["details"]["coverage_gaps"]) == 8


def test_on_save_scopes_to_only_the_saved_file(tmp_path: Path, monkeypatch):
    repo = _init_repo(tmp_path)
    app_dir = repo / "app"
    app_dir.mkdir()
    (app_dir / "__init__.py").write_text("", encoding="utf-8")
    (app_dir / "a.py").write_text("def a():\n    return 1\n", encoding="utf-8")
    (app_dir / "b.py").write_text("def b():\n    return 2\n", encoding="utf-8")
    (repo / "tests").mkdir()

    monkeypatch.setattr(ai_client, "generate", lambda prompt, **k: "def test_a():\n    assert a() == 1\n")

    result = test_maintenance.run(
        target=str(repo), stage="on-save", changed_file=str(app_dir / "a.py")
    )

    functions = {g["function"] for g in result["details"]["generated"]}
    assert functions == {"a"}
    assert not (repo / "tests" / "test_b.py").exists()


