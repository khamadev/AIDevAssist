def test_run_redacts_secrets_before_they_reach_the_ai_prompt(tmp_path: Path, monkeypatch):
    repo = _init_repo(tmp_path)
    app_dir = repo / "app"
    app_dir.mkdir()
    (app_dir / "__init__.py").write_text("", encoding="utf-8")
    source = app_dir / "config.py"
    source.write_text(
        "def get_headers():\n"
        '    api_key = "sk-live-abcdef123456"\n'
        '    return {"Authorization": f"Bearer {api_key}"}\n',
        encoding="utf-8",
    )
    (repo / "tests").mkdir()
    _stage(repo, source)

    captured_prompts = []

    def _fake_generate(prompt, **k):
        captured_prompts.append(prompt)
        return "def test_get_headers():\n    assert 'Authorization' in get_headers()\n"

    monkeypatch.setattr(ai_client, "generate", _fake_generate)

    result = test_maintenance.run(target=str(repo), stage="pre-commit")

    assert "sk-live-abcdef123456" not in captured_prompts[0]
    assert all("sk-live-abcdef123456" not in p for p in captured_prompts)
    assert result["details"]["generated"][0]["secrets_redacted"] is True
    assert "secrets redacted" in result["summary"]


def test_generated_tests_are_syntactically_valid_and_pass(tmp_path: Path, monkeypatch):
    repo = _init_repo(tmp_path)
    source = _seed_source(repo)
    _stage(repo, source)
    monkeypatch.setattr(ai_client, "generate", lambda prompt, **k: GENERATED_TEST)

    test_maintenance.run(target=str(repo), stage="pre-commit")

    result = subprocess.run(
        [sys.executable, "-m", "pytest", "-q", "tests/test_trip_logic.py"],
        cwd=repo,
        capture_output=True,
        text=True,
    )
    assert result.returncode == 0, result.stdout + result.stderr
