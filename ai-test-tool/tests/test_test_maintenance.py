import subprocess
import sys
from pathlib import Path

import pytest

from ai_test_tool import ai_client
from ai_test_tool.agents import test_maintenance

GENERATED_TEST = '''def test_trips_overlap_true_for_touching_ranges():
    from datetime import date
    assert trips_overlap(date(2026, 1, 1), date(2026, 1, 5), date(2026, 1, 5), date(2026, 1, 7))


def test_trips_overlap_false_for_disjoint_ranges():
    from datetime import date
    assert not trips_overlap(date(2026, 1, 1), date(2026, 1, 2), date(2026, 1, 5), date(2026, 1, 7))
'''


def _init_repo(tmp_path: Path) -> Path:
    subprocess.run(["git", "init", "-q"], cwd=tmp_path, check=True)
    subprocess.run(["git", "config", "user.email", "test@example.com"], cwd=tmp_path, check=True)
    subprocess.run(["git", "config", "user.name", "Test"], cwd=tmp_path, check=True)
    return tmp_path


def _seed_source(tmp_path: Path) -> Path:
    app_dir = tmp_path / "app"
    app_dir.mkdir()
    (app_dir / "__init__.py").write_text("", encoding="utf-8")
    source = app_dir / "trip_logic.py"
    source.write_text(
        "from datetime import date\n\n\n"
        "def trip_duration_days(start_date: date, end_date: date) -> int:\n"
        "    return (end_date - start_date).days + 1\n\n\n"
        "def trips_overlap(start_a: date, end_a: date, start_b: date, end_b: date) -> bool:\n"
        "    return start_a <= end_b and start_b <= end_a\n\n\n"
        "def _internal_helper(x):\n"
        "    return x\n",
        encoding="utf-8",
    )
    (tmp_path / "tests").mkdir()
    (tmp_path / "tests" / "__init__.py").write_text("", encoding="utf-8")
    return source


def _stage(repo: Path, *paths: Path) -> None:
    subprocess.run(["git", "add", *[str(p) for p in paths]], cwd=repo, check=True)


def test_run_reports_nothing_to_scan_with_no_changed_files(tmp_path: Path):
    _init_repo(tmp_path)

    result = test_maintenance.run(target=str(tmp_path), stage="pre-commit")

    assert result["passed"] is True
    assert result["details"]["generated"] == []


def test_run_generates_tests_for_untested_functions_via_ai(tmp_path: Path, monkeypatch):
    repo = _init_repo(tmp_path)
    source = _seed_source(repo)
    _stage(repo, source)

    monkeypatch.setattr(ai_client, "generate", lambda prompt, **k: GENERATED_TEST)

    result = test_maintenance.run(target=str(repo), stage="pre-commit")

    generated = result["details"]["generated"]
    assert {g["function"] for g in generated} == {"trip_duration_days", "trips_overlap"}
    assert [Path(p).as_posix() for p in result["details"]["generated_test_paths"]] == [
        "tests/test_trip_logic.py"
    ]

    test_content = (repo / "tests" / "test_trip_logic.py").read_text(encoding="utf-8")
    assert "AI-generated by ai-test-tool" in test_content
    assert "trips_overlap" in test_content


